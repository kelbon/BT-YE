/*
Запускает акторов и выполняет `main` на акторе 0. Одновременно может выполняться только один `run`.

- вызывающий поток - актор 0, остальные - новые потоки
- `main` запускается, когда контексты всех акторов созданы и фабрика разрушена
-  пока идёт `main` циклы всех акторов живы. Она может использовать jump_on
- завершение `main` вызывает request_stop(). Исключение из `main` или колбэка at_exit - лог и код 1
- цикл актора удерживается через ioctx().start_task() до снятия удержаний остановкой, затем заканчивается,
  когда у контекста не осталось работы. Открытые сокеты, таймеры и т.п. держат его, останавливать их -
  дело пользователя. Исключение из цикла - std::terminate
- контекст разрушается на потоке актора, когда закончились циклы всех акторов
- `run` возвращается, когда закончились циклы всех акторов, с кодом `main`
*/
int run(app_options, aa::move_only_fn<dd::task<int>()> main,
        actor_context_factory_t = default_actor_context_factory());

/*
Останавливает акторов. Можно вызывать только с потока актора
Повторный вызов и вызов после stopped() своего актора ничего не делают.

1. корутина остановки проходит по акторам по очереди (0, 1, ...), на потоке каждого: ставит флаг
   actor::stopped() и вызывает actor::at_exit этого актора в порядке обратном регистрации
2. когда калбеки выполнены на всех акторах и не осталось фоновых задач (run_in_background, в том числе
   `main`), удержания циклов всех акторов снимаются. До этого момента циклы всех акторов живы и прыгать
   можно куда угодно

Контракт: после снятия удержаний задачи не прыгают на другие акторы и не запускают фоновые задачи -
цикл, на который они попадут, мог уже закончиться. Всё, что должно пережить остановку, - фоновые задачи
*/
void request_stop() noexcept;

